def pick_lang(code: str | None) -> str:
    # 'de-AT' -> 'de', anything else -> en
    base = (code or "").split("-")[0].lower()
    return base if base in TEXTS else FALLBACK


def _template(lang: str, key: str) -> str:
    return TEXTS.get(lang, TEXTS[FALLBACK]).get(key) or TEXTS[FALLBACK][key]


def t(lang: str, key: str, **values: object) -> str:
    return _template(lang, key).format(**{k: html.escape(str(v)) for k, v in values.items()})


def plain(lang: str, key: str, **values: object) -> str:
    return _template(lang, key).format(**{k: str(v) for k, v in values.items()})
